const defaultLocale = 'ar';

export function getTranslation(locale = defaultLocale) {
  return translations[locale] || translations.ar;
}

export function tFrom(locale) {
  const strings = getTranslation(locale);
  return function t(key) {
    const keys = key.split('.');
    let v = strings;
    for (const k of keys) {
      v = v?.[k];
    }
    return v ?? key;
  };
}
